BUCKETS = {512: ASPECT_RATIO_512, 1024: ASPECT_RATIO_1024, 2048: ASPECT_RATIO_2048}


def closest_size(height, width, bucket=1024):
    """Return (height, width) of the vendor bucket closest to the given aspect ratio."""
    table = BUCKETS[min(BUCKETS, key=lambda b: abs(b - bucket))]
    ratio = height / max(width, 1)
    key = min(table, key=lambda r: abs(float(r) - ratio))
    h, w = table[key]
    return int(h), int(w)
